def discounted_return(rewards, gamma):
    """Discounted sum over the last axis: rewards [..., T] -> returns [...]."""
    T = rewards.shape[-1]
    discounts = gamma ** torch.arange(T, dtype=rewards.dtype)   # [T]
    return (rewards * discounts).sum(-1)


