def evaluate_context(model, tasks, tok, keep_obs=None, n_samples=16, seed=7, cfg=None):
    """Behavior statistics of n_samples episodes per task, sampled with context_view(keep_obs) and renamed tasks."""
    cfg, names = cfg or _grpo.RLConfig(), random.Random(seed)
    batch_tasks = [_grpo.randomize_names(t, names) for t in tasks for _ in range(n_samples)]
    trajs, _ = context_rollout_batch(model, [_grpo.make_env(cfg) for _ in batch_tasks], batch_tasks, tok, keep_obs,
                                     cfg.max_turns, cfg.temperature, torch.Generator().manual_seed(seed))
    return _grpo.behavior_stats(trajs)


