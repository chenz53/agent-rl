def compact_source(source):
    """Projection of source for the read tool: tokens space-separated, lines kept, indentation dropped."""
    pattern = r'\d+|\w+|==|>=|<=|!=|//|\+=|\*=|[^\s\w]'
    return '\n'.join(' '.join(re.findall(pattern, line)) for line in source.strip().split('\n'))


