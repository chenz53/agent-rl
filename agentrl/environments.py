def parse_call(text):
    """Parse '<call> tool [arg] </call>' -> (tool, arg or None); None if malformed."""
    words = text.split()
    if len(words) not in (3, 4) or words[0] != '<call>' or words[-1] != '</call>':
        return None
    return words[1], (words[2] if len(words) == 4 else None)


