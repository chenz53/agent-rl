def gae_advantages(rewards, values, mask, gamma=1.0, lam=0.95):
    """GAE over policy tokens only: rewards, values, mask [B, T] -> (advantages, returns) [B, T], 0 off-mask.

    Tool and other off-mask positions are skipped: delta_t uses the value at the NEXT policy position,
    and the recursion A_t = delta_t + gamma * lam * A_next chains across them. The value after the
    last policy token is 0 (the episode ended); bootstrap truncated episodes before calling this.
    """
    B, T = rewards.shape
    advantages = torch.zeros_like(rewards)
    next_value = torch.zeros(B, dtype=rewards.dtype)               # V at the next policy position
    next_adv = torch.zeros(B, dtype=rewards.dtype)                 # A at the next policy position
    for t in reversed(range(T)):
        on = mask[:, t] > 0
        delta = rewards[:, t] + gamma * next_value - values[:, t]
        adv = delta + gamma * lam * next_adv
        next_adv = torch.where(on, adv, next_adv)                   # carry across tool positions
        next_value = torch.where(on, values[:, t], next_value)
        advantages[:, t] = next_adv * mask[:, t]
    return advantages, (advantages + values) * mask


