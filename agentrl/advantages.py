def returns_to_go(rewards, mask, gamma=1.0):
    """Discounted return-to-go over policy tokens only: rewards, mask [B, T] -> [B, T], 0 off-mask."""
    out = torch.zeros_like(rewards)
    running = torch.zeros(rewards.shape[0], dtype=rewards.dtype)   # [B] return from the next policy token
    for t in reversed(range(rewards.shape[1])):
        on = mask[:, t] > 0
        running = torch.where(on, rewards[:, t] + gamma * running, running)   # skip tool positions
        out[:, t] = running * mask[:, t]
    return out


