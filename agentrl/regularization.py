def entropy_bonus(logits, mask):
    """Mean full-vocabulary entropy over policy positions: logits [B, T, V], mask [B, T] -> differentiable scalar."""
    return _policy_gradient.masked_mean(_policy.entropy_from_logits(logits), mask)


