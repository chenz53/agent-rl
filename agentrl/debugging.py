def minibatch_backward(model, batch, rows, mask, old_logp, advantages, cfg, bug=None, ref_model=None):
    """Loss and backward for one minibatch, no optimizer step -> stats dict (clip_frac, ..., entropy, loss)."""
    ids = batch['ids']
    parts = rows[mask[rows].sum(-1).argsort()].chunk(4) if bug == 'accum_local' else [rows]
    logs = []
    for part in parts:
        logits = model(ids[part])[:, :-1] / cfg.temperature                    # [b, T-1, V]
        logp = _policy.selected_log_probs(logits, ids[part, 1:])
        loss, stats = _grpo.policy_loss(logp, old_logp[part], advantages[part], mask[part], cfg)
        if bug == 'entropy_sign':
            loss = loss + ENTROPY_COEF * _regularization.entropy_bonus(logits, mask[part])
        if ref_model is not None:
            with torch.no_grad():
                ref_logp = _policy.selected_log_probs(ref_model(ids[part])[:, :-1] / cfg.temperature, ids[part, 1:])
            kl = _policy_gradient.masked_mean(_grpo.kl_penalty(logp, ref_logp, cfg.kl_kind), mask[part])
            loss, stats['kl_ref'] = loss + cfg.kl_coef * kl, kl.item()
        (loss / len(parts)).backward()
        stats['entropy'] = _policy_gradient.masked_mean(_policy.entropy_from_logits(logits.detach()), mask[part]).item()
        logs.append(dict(stats, loss=loss.item()))
    return {k: sum(s[k] for s in logs) / len(logs) for k in logs[0]}


