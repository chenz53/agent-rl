def masked_mean(x, mask, dim=None):
    """Mean of x where mask is 1: x, mask [B, T] -> scalar (dim=None) or reduced over dim."""
    if dim is None:
        return (x * mask).sum() / mask.sum().clamp(min=1e-8)
    return (x * mask).sum(dim) / mask.sum(dim).clamp(min=1e-8)


