def make_base_agent(tok, seed=0, kinds=('random', 'blind'), episodes_per_task=8, steps=200,
                    batch_size=32, lr=3e-3):
    """TinyAgent behavior-cloned on well-formed but unskilled scripted play on the train tasks."""
    torch.manual_seed(seed)
    gen = torch.Generator().manual_seed(seed)
    demos = []
    for k, kind in enumerate(kinds):
        policy = _environments.scripted_policy(kind, seed=seed + k)
        demos += [_trajectories.scripted_rollout(policy, _environments.BugFixEnv(), task, tok)
                  for task in _environments.make_tasks('train') for _ in range(episodes_per_task)]
    data = _trajectories.collate(demos, tok.pad_id)                              # ids [N, T], action_mask [N, T-1]
    model = _policy.TinyAgent(tok.vocab_size)
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    for _ in range(steps):
        idx = torch.randint(len(demos), (batch_size,), generator=gen)
        logp = _policy.sequence_log_probs(model, data['ids'][idx])         # [b, T-1]
        loss = -masked_mean(logp, data['action_mask'][idx])            # cross-entropy on policy tokens
        opt.zero_grad()
        loss.backward()
        opt.step()
    return model


