def entropy_from_logits(logits):
    """Entropy of softmax(logits) over the last axis: [..., V] -> [...]."""
    logp = torch.log_softmax(logits.float(), dim=-1)
    p = logp.exp()
    return -(p * torch.where(p > 0, logp, 0.0)).sum(-1)   # 0 * log 0 := 0


