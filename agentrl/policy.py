def sequence_log_probs(model, ids):
    """Log-probs of ids[:, 1:] given their prefixes: ids [B, T] -> [B, T-1]."""
    logits = model(ids)                                   # [B, T, V]
    return selected_log_probs(logits[:, :-1], ids[:, 1:])


