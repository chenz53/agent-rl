class EditBudgetEnv(_environments.BugFixEnv):
    """BugFixEnv that applies at most max_edits edits per episode; later edits use a turn and change nothing."""
    def __init__(self, max_turns=6, reward='hidden', max_edits=1):
        super().__init__(max_turns, reward)
        self.max_edits = max_edits

    def step(self, action_text):
        call = _environments.parse_call(action_text)
        refused = call is not None and call[0] == 'edit' and call[1] in _environments.EDIT_OPS \
            and len(self.ops) >= self.max_edits
        if not refused:
            return super().step(action_text)
        self.turn += 1
        self.done = self.turn >= self.max_turns
        if not self.done:
            return _environments.MESSAGES['unchanged'], 0.0, False, {'turn': self.turn, 'event': 'refused'}
        info = self.final_info(submitted=False)
        return _environments.MESSAGES['unchanged'], self.reward_fn(info), True, info


