def outcome_rewards(rewards, mask):
    """Place each trajectory's reward [B] on its last policy token -> [B, T], zero elsewhere."""
    T = mask.shape[-1]
    last = (mask * torch.arange(1, T + 1)).argmax(-1)              # [B] index of the last 1 in each row
    out = torch.zeros(mask.shape, dtype=rewards.dtype)
    out[torch.arange(len(rewards)), last] = rewards
    return out * mask                                               # rows without policy tokens stay zero

def returns_to_go(rewards, mask, gamma=1.0):
    """Discounted return-to-go over policy tokens only: rewards, mask [B, T] -> [B, T], 0 off-mask."""
    out = torch.zeros_like(rewards)
    running = torch.zeros(rewards.shape[0], dtype=rewards.dtype)   # [B] return from the next policy token
    for t in reversed(range(rewards.shape[1])):
        on = mask[:, t] > 0
        running = torch.where(on, rewards[:, t] + gamma * running, running)   # skip tool positions
        out[:, t] = running * mask[:, t]
    return out

def gae_advantages(rewards, values, mask, gamma=1.0, lam=0.95):
    """GAE over policy tokens only: rewards, values, mask [B, T] -> (advantages, returns) [B, T], 0 off-mask.

    Tool and other off-mask positions are skipped: delta_t uses the value at the NEXT policy position,
    and the recursion A_t = delta_t + gamma * lam * A_next chains across them. The value after the
    last policy token is 0 (the episode ended); bootstrap truncated episodes before calling this.
    """
    B, T = rewards.shape
    advantages = torch.zeros_like(rewards)
    next_value = torch.zeros(B, dtype=rewards.dtype)               # V at the next policy position
    next_adv = torch.zeros(B, dtype=rewards.dtype)                 # A at the next policy position
    for t in reversed(range(T)):
        on = mask[:, t] > 0
        delta = rewards[:, t] + gamma * next_value - values[:, t]
        adv = delta + gamma * lam * next_adv
        next_adv = torch.where(on, adv, next_adv)                   # carry across tool positions
        next_value = torch.where(on, values[:, t], next_value)
        advantages[:, t] = next_adv * mask[:, t]
    return advantages, (advantages + values) * mask

def make_critic(model):
    """Value model: a copy of a TinyAgent whose output head has one unit (ids [B, T] -> [B, T, 1])."""
    critic = copy.deepcopy(model)
    critic.head = nn.Linear(critic.head.in_features, 1)
    return critic


def critic_values(critic, ids):
    """Values of the prefixes that predict ids[:, 1:]: ids [B, T] -> [B, T-1]."""
    return critic(ids)[..., 0][:, :-1]


def explained_variance(pred, target, mask):
    """1 - Var(target - pred) / Var(target) over masked positions; 1 is perfect, <= 0 is useless."""
    on = mask > 0
    return (1 - (target - pred)[on].var() / target[on].var()).item()

def group_advantages(rewards, group_size, normalize_std=True, eps=1e-6):
    """GRPO-style advantages: rewards [B] in consecutive groups of G -> (r - group mean) [/ group std], [B]."""
    r = rewards.view(-1, group_size)                                # [B/G, G]
    adv = r - r.mean(-1, keepdim=True)
    if normalize_std:
        adv = adv / (r.std(-1, keepdim=True) + eps)                 # sample std (Bessel), as torch.std
    return adv.flatten()


def rloo_advantages(rewards, group_size):
    """Leave-one-out advantages: r_i - mean of the other G-1 rewards in its group -> [B]."""
    r = rewards.view(-1, group_size)
    return (r - (r.sum(-1, keepdim=True) - r) / (group_size - 1)).flatten()

def turn_advantages(rewards, values, mask, turn_ids, gamma=1.0, lam=0.95):
    """Turn-level GAE: one value per call (at its first token), rewards summed per call -> [B, T] on policy tokens."""
    first = mask * (1 - F.pad(mask, (1, 0))[:, :-1])                       # 1 at the first token of each call
    turn = turn_ids.clamp(min=0)                                            # prompt (-1) is masked out anyway
    K = int(turn.max()) + 1
    turn_rewards = torch.zeros(len(mask), K, dtype=rewards.dtype).scatter_add_(1, turn, rewards * mask)
    turn_values = torch.zeros(len(mask), K, dtype=values.dtype).scatter_add_(1, turn, values * first)
    turn_mask = torch.zeros(len(mask), K, dtype=mask.dtype).scatter_add_(1, turn, first)
    adv, _ = gae_advantages(turn_rewards, turn_values, turn_mask, gamma, lam)   # [B, K]
    return adv.gather(1, turn) * mask


