# ---------------------------------------------------------------- the repository of one episode
@dataclasses.dataclass
class Repo:
    """One episode's files {name: text}, the files Read so far, and the task they come from."""
    task: arl.Task
    files: dict
    read: set = dataclasses.field(default_factory=set)


def test_file(task):
    """pytest-style public tests for task.fn_name; one test function per (args, expected) pair."""
    lines = [f'from {task.fn_name} import {task.fn_name}', '']
    for k, (args, want) in enumerate(task.public_tests):
        call = f"{task.fn_name}({', '.join(map(repr, args))})"
        lines += ['', f'def test_{task.fn_name}_{k}():', f'    got = {call}',
                  f"    assert got == {want!r}, f'{call} returned {{got!r}}, expected {want!r}'", '']
    return '\n'.join(lines)


def make_repo(task):
    """Source file and public test file only; the hidden tests stay outside the repository."""
    return Repo(task, {f'{task.fn_name}.py': task.source, f'test_{task.fn_name}.py': test_file(task)})


def user_message(task):
    return (f'Issue: {task.fn_name} in {task.fn_name}.py returns wrong results. Fix the bug. '
            f'The public tests are in test_{task.fn_name}.py. Use the tools to read the code, fix it, and run the tests.')


# ---------------------------------------------------------------- process isolation for model-written code
RUNNER = r'''
import importlib.util, json, os, resource, sys
limits = json.loads(sys.argv[1])
for name, value in limits.items():                       # before any repository code is imported
    resource.setrlimit(getattr(resource, name), (value, value))
sys.path.insert(0, os.getcwd())
mode, arg = sys.argv[2], sys.argv[3]

def load(path):
    name = os.path.splitext(os.path.basename(path))[0]
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module

if mode == 'pytest':
    counts = dict(passed=0, failed=0, error=0)
    for path in json.loads(arg):
        try:
            module = load(path)
        except BaseException as e:
            print(f'ERROR collecting {path} - {type(e).__name__}: {e}')
            counts['error'] += 1
            continue
        for name in [n for n, v in vars(module).items() if n.startswith('test') and callable(v)]:
            try:
                getattr(module, name)()
                print(f'{path}::{name} PASSED')
                counts['passed'] += 1
            except BaseException as e:
                print(f'{path}::{name} FAILED - {type(e).__name__}: {e}')
                counts['failed'] += 1
    print(', '.join(f'{v} {k}' for k, v in counts.items() if v) or 'no tests ran')
elif mode == 'script':
    import runpy
    runpy.run_path(arg, run_name='__main__')
elif mode == 'grade':
    job = json.loads(sys.stdin.read())
    def check(fn, tests):
        out = []
        for args, want in tests:
            try:
                got = fn(*args)
                out.append(type(got) == type(want) and got == want)
            except BaseException:
                out.append(False)
        return out
    try:
        fn = getattr(load(job['file']), job['fn'])
        result = dict(public=check(fn, job['public']), hidden=check(fn, job['hidden']))
    except BaseException as e:
        result = dict(public=[False] * len(job['public']), hidden=[False] * len(job['hidden']), error=repr(e))
    print(job['nonce'] + json.dumps(result))
'''
LIMITS = dict(RLIMIT_CPU=5, RLIMIT_AS=1 << 30, RLIMIT_FSIZE=1 << 20, RLIMIT_NPROC=0)


def sandbox_run(files, mode, arg, timeout=10.0, stdin=''):
    """Run RUNNER in a child process over a fresh copy of files -> (combined output, timed_out)."""
    workdir = tempfile.mkdtemp(prefix='bugfix-')
    try:
        for name, text in files.items():
            Path(workdir, name).write_text(text)
        cmd = [sys.executable, '-I', '-S', '-B', '-c', RUNNER, json.dumps(LIMITS), mode, arg]
        env = {'PATH': '/usr/bin:/bin', 'HOME': workdir, 'LANG': 'C.UTF-8'}    # no inherited variables
        try:
            done = subprocess.run(cmd, cwd=workdir, env=env, input=stdin, capture_output=True, text=True,
                                  timeout=timeout)
            status = '' if done.returncode == 0 else f'\n(exit status {done.returncode})'   # -24: CPU limit
            return done.stdout + done.stderr + status, False
        except subprocess.TimeoutExpired:
            return f'Command timed out after {timeout:.0f}s', True
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


def grade(repo):
    """Public and hidden test results of the final <fn>.py, computed in a child process -> dict."""
    task, nonce = repo.task, f'@@{random.getrandbits(64):016x}@@'
    files = {f'{task.fn_name}.py': repo.files.get(f'{task.fn_name}.py', '')}   # the source file only
    job = dict(file=f'{task.fn_name}.py', fn=task.fn_name, nonce=nonce, public=task.public_tests,
               hidden=task.hidden_tests)
    out, _ = sandbox_run(files, 'grade', '', stdin=json.dumps(job))
    line = next((l for l in out.splitlines() if l.startswith(nonce)), None)
    result = json.loads(line[len(nonce):]) if line else dict(public=[False], hidden=[False])
    return dict(public_pass=all(result['public']), hidden_pass=all(result['hidden']))


# ---------------------------------------------------------------- the tools
class ToolError(Exception):
    """A well-formed call that fails, like an Edit whose old_string is absent; kind names the failure."""
    def __init__(self, kind, message):
        super().__init__(message)
        self.kind = kind


def resolve(repo, path, must_exist=True):
    name = str(path).strip()
    for prefix in (ROOT + '/', './'):
        name = name[len(prefix):] if name.startswith(prefix) else name
    if must_exist and name not in repo.files:
        raise ToolError('missing_file', f'File does not exist: {path}')
    return name


def numbered(text, start=1):
    return '\n'.join(f'{i:6d}\t{line}' for i, line in enumerate(text.split('\n'), start))


def tool_read(repo, file_path, offset=1, limit=2000):
    name = resolve(repo, file_path)
    repo.read.add(name)
    lines = repo.files[name].split('\n')
    start = max(int(offset), 1)
    return numbered('\n'.join(lines[start - 1:start - 1 + int(limit)]), start)


def tool_edit(repo, file_path, old_string, new_string, replace_all=False):
    name = resolve(repo, file_path)
    if name not in repo.read:
        raise ToolError('not_read', 'File has not been read yet. Read it first before writing to it.')
    if old_string == new_string:
        raise ToolError('no_change', 'No changes to make: old_string and new_string are exactly the same.')
    count = repo.files[name].count(old_string) if old_string else 0
    if count == 0:
        raise ToolError('not_found', f'String to replace not found in file.\nString: {old_string}')
    if count > 1 and not replace_all:
        raise ToolError('not_unique', f'Found {count} matches of the string to replace, but replace_all is false. '
                        'To replace all occurrences, set replace_all to true. To replace only one occurrence, '
                        'please provide more context to uniquely identify the instance.')
    repo.files[name] = repo.files[name].replace(old_string, new_string, -1 if replace_all else 1)
    return (f'The file {ROOT}/{name} has been updated. Here\'s the result of running `cat -n` on the edited file:\n'
            + numbered(repo.files[name]))


def tool_write(repo, file_path, content):
    name = resolve(repo, file_path, must_exist=False)
    if '/' in name or not name:
        raise ToolError('bad_path', f'Cannot write outside the repository root: {file_path}')
    if name in repo.files and name not in repo.read:
        raise ToolError('not_read', 'File has not been read yet. Read it first before writing to it.')
    repo.files[name] = content
    repo.read.add(name)
    return f'File created successfully at: {ROOT}/{name}'


UNAVAILABLE = 'command not available in this sandbox (available: pytest, python <file>.py, ls, cat, grep)'


def bash_one(repo, words, timeout):
    """One allowlisted command, emulated; only pytest and python run code, in a child process."""
    if words[0] == 'cd' and len(words) <= 2 and (len(words) == 1 or words[1] in (ROOT, ROOT + '/', '.', '~')):
        return ''
    if words[0] == 'ls':
        return '\n'.join(sorted(repo.files))
    if words[0] == 'cat' and len(words) > 1:
        return '\n'.join(repo.files[resolve(repo, w)] for w in words[1:] if not w.startswith('-'))
    if words[0] == 'grep' and len(words) > 1:
        flags = {w for w in words[1:] if w.startswith('-')}
        args = [w for w in words[1:] if not w.startswith('-')]
        pattern = re.compile(args[0], re.I if '-i' in ''.join(flags) else 0)
        names = [resolve(repo, w) for w in args[1:] if w not in ('.', ROOT)] or sorted(repo.files)
        hits = [f"{n}:{f'{i}:' if '-n' in flags else ''}{line}" for n in names
                for i, line in enumerate(repo.files[n].split('\n'), 1) if pattern.search(line)]
        return '\n'.join(hits)
    if words[:3] in (['python', '-m', 'pytest'], ['python3', '-m', 'pytest']):
        words = words[2:]
    if words[0] == 'pytest':
        targets = [w.split('::')[0] for w in words[1:] if not w.startswith('-')]
        names = [resolve(repo, w) for w in targets if w not in ('.', ROOT, ROOT + '/')] or \
            sorted(n for n in repo.files if n.startswith('test') and n.endswith('.py'))
        return sandbox_run(repo.files, 'pytest', json.dumps(names), timeout)[0]
    if words[0] in ('python', 'python3') and len(words) == 2 and words[1].endswith('.py'):
        name = resolve(repo, words[1])
        if name.startswith('test'):                               # a test file runs its tests
            return sandbox_run(repo.files, 'pytest', json.dumps([name]), timeout)[0]
        return sandbox_run(repo.files, 'script', name, timeout)[0]
    raise ToolError('unavailable', f'Error: {" ".join(words)}: {UNAVAILABLE}')


def tool_bash(repo, command, timeout=None):
    timeout = min(float(timeout) / 1000, 10.0) if timeout else 10.0
    try:
        segments = [shlex.split(s) for s in command.split('&&')]
    except ValueError as e:
        raise ToolError('unavailable', f'Error: cannot parse command: {e}')
    if any(not s or any(t in ('|', ';', '>', '>>', '<') for t in s) for s in segments):
        raise ToolError('unavailable', f'Error: {UNAVAILABLE}; pipes and redirections are not supported')
    outputs = [bash_one(repo, [w for w in s if w != '2>&1'], timeout) for s in segments]
    return '\n'.join(o for o in outputs if o) or '(no output)'


TOOL_FNS = {'Read': tool_read, 'Edit': tool_edit, 'Write': tool_write, 'Bash': tool_bash}
SPECS = {t['function']['name']: t['function']['parameters'] for t in TOOLS}


def parse_call(body):
    """JSON body of one <tool_call> -> (name, arguments) or None if it does not match a tool schema."""
    try:
        call = json.loads(body)
    except json.JSONDecodeError:
        return None
    if not isinstance(call, dict) or call.get('name') not in TOOL_FNS or not isinstance(call.get('arguments', {}), dict):
        return None
    spec, args = SPECS[call['name']], call.get('arguments', {})
    if any(r not in args for r in spec['required']) or any(
            k not in spec['properties'] or not isinstance(v, PARAM_TYPES[spec['properties'][k]['type']])
            for k, v in args.items()):
        return None
    return call['name'], args


def execute(repo, text, stats):
    """Run the tool calls of one assistant turn -> list of observations ([] means a final answer)."""
    if '<tool_call>' not in text:
        return []
    observations = []
    bodies = CALL.findall(text) or [None]                      # an unclosed <tool_call> is one malformed call
    for body in bodies[:MAX_CALLS_PER_TURN]:
        call = parse_call(body) if body is not None else None
        if call is None:
            stats['malformed'] += 1
            observations.append('Error: the tool call is not valid JSON matching one of the tool schemas.')
            continue
        name, args = call
        stats[f'calls_{name}'] += 1
        try:
            observations.append(TOOL_FNS[name](repo, **args)[:MAX_OBS_CHARS])
            if name in ('Edit', 'Write') and repo.files.get(f'{repo.task.fn_name}.py') != repo.task.source:
                stats['source_changed'] = 1
        except ToolError as e:
            stats['failed'] += 1
            stats[f'failed_{e.kind}'] += 1
            observations.append(f'<tool_use_error>{e}</tool_use_error>')
        except (KeyError, ValueError, re.error, TypeError) as e:
            stats['failed'] += 1
            stats['failed_other'] += 1
            observations.append(f'<tool_use_error>{type(e).__name__}: {e}</tool_use_error>')
    return observations


# ---------------------------------------------------------------- template and token path
def obs_text(observations):
    """Template-owned text that closes an assistant turn, carries tool results, and opens the next turn."""
    blocks = ''.join(f'\n<tool_response>\n{o}\n</tool_response>' for o in observations)
    return f'\n<|im_start|>user{blocks}<|im_end|>\n<|im_start|>assistant\n<think>\n\n</think>\n\n'


def prompt_ids(qtok, task):
    messages = [{'role': 'system', 'content': SYSTEM}, {'role': 'user', 'content': user_message(task)}]
    text = qtok.apply_chat_template(messages, tools=TOOLS, tokenize=False, add_generation_prompt=True,
                                    enable_thinking=False)
    return qtok(text, add_special_tokens=False).input_ids


def check_template(qtok):
    """Assert that prompt + turn + obs_text tokens equal the real template's rendering, for 1 and 2 results."""
    task = arl.make_tasks('train')[0]
    for results in (['     1\tdef f(x):'], ['ok', 'Error: x']):
        calls = [{'type': 'function', 'function': {'name': 'Read', 'arguments': {'file_path': 'f.py'}}}] * len(results)
        messages = [{'role': 'system', 'content': SYSTEM}, {'role': 'user', 'content': user_message(task)},
                    {'role': 'assistant', 'content': '', 'tool_calls': calls}] + \
                   [{'role': 'tool', 'content': r} for r in results]
        full = qtok.apply_chat_template(messages, tools=TOOLS, tokenize=False, add_generation_prompt=True,
                                        enable_thinking=False)
        cut = full.index('<|im_end|>', full.index('<|im_start|>assistant')) + len('<|im_end|>')
        assert full[cut:] == obs_text(results), repr(full[cut:])
        head = qtok(full[:cut], add_special_tokens=False).input_ids
        assert qtok(full, add_special_tokens=False).input_ids == head + qtok(obs_text(results),
                                                                             add_special_tokens=False).input_ids
        assert qtok(full[:full.index('<|im_start|>assistant')] + '<|im_start|>assistant\n<think>\n\n</think>\n\n',
                    add_special_tokens=False).input_ids == prompt_ids(qtok, task)


# ---------------------------------------------------------------- rollout (token-in/token-out)
class RecordLogp:
    """Logits processor that keeps only the previous step's log-softmax and gathers the sampled token's log-prob.

    Storing every step's [B, 151936] logits (output_logits=True) costs ~0.6 MB per row per token; this keeps one step.
    """
    def __init__(self):
        self.prev, self.picked = None, []

    def __call__(self, input_ids, scores):
        if self.prev is not None:
            self.picked.append(self.prev.gather(-1, input_ids[:, -1:]).squeeze(-1))
        self.prev = torch.log_softmax(scores.float(), -1)
        return scores


@torch.no_grad()
def generate(model, qtok, prefixes, max_new_tokens, seed):
    """One assistant turn per prefix (lists of ids), left-padded -> [(new ids, sampler log-probs)] per row."""
    width = max(len(p) for p in prefixes)
    ids = torch.tensor([[PAD] * (width - len(p)) + p for p in prefixes], device='cuda')
    attn = torch.tensor([[0] * (width - len(p)) + [1] * len(p) for p in prefixes], device='cuda')
    torch.manual_seed(seed)
    record = RecordLogp()
    seq = model.generate(input_ids=ids, attention_mask=attn, do_sample=True, temperature=1.0, top_p=1.0, top_k=0,
                         max_new_tokens=max_new_tokens, eos_token_id=[IM_END, ENDOFTEXT], pad_token_id=PAD,
                         logits_processor=LogitsProcessorList([record]))
    new = seq[:, width:]                                                             # [B, n]
    record.picked.append(record.prev.gather(-1, new[:, -1:]).squeeze(-1))
    logp = torch.stack(record.picked, 1)                                             # [B, n]
    rows = []
    for b in range(len(prefixes)):
        row = new[b].tolist()
        end = next((i + 1 for i, t in enumerate(row) if t in (IM_END, ENDOFTEXT)), len(row))
        rows.append((row[:end], logp[b, :end].tolist()))
    return rows


def rollout(model, qtok, tasks, cfg, args, seed, pool):
    """Episodes for tasks in lockstep -> list of arl.Trajectory with info (stats, reward, decoded turns)."""
    names = random.Random(seed)
    tasks = [arl.randomize_names(t, names) if cfg.rename else t for t in tasks]
    eps = []
    for task in tasks:
        ids = prompt_ids(qtok, task)
        eps.append(dict(repo=make_repo(task), ids=ids, mask=[0] * len(ids), logp=[0.0] * len(ids),
                        turn=[-1] * len(ids), stats=collections.Counter(), done=False, answered=False, texts=[]))
    for turn in range(args.max_turns):
        active = [e for e in eps if not e['done']]
        if not active:
            break
        active.sort(key=lambda e: len(e['ids']))                  # similar lengths per chunk: less padding
        outs = []
        for c in range(0, len(active), args.gen_batch):
            chunk = active[c:c + args.gen_batch]
            outs += generate(model, qtok, [e['ids'] for e in chunk], args.max_new_tokens, seed * 1000 + turn * 10 + c)
        for e, (new, logp) in zip(active, outs):
            new_mask = [1] * len(new)
            if new[-1] not in (IM_END, ENDOFTEXT):          # cut off at max_new_tokens: close the turn (template-owned)
                new, new_mask, logp = new + [IM_END], new_mask + [0], logp + [0.0]
                e['stats']['truncated'] += 1
            e['ids'] += new
            e['mask'] += new_mask
            e['logp'] += logp
            e['turn'] += [turn] * len(new)
            e['texts'].append(qtok.decode(new))
        results = list(pool.map(lambda e: execute(e['repo'], e['texts'][-1], e['stats']), active))
        for e, observations in zip(active, results):
            e['stats']['turns'] += 1
            if not observations:
                e['done'] = e['answered'] = True
            elif turn == args.max_turns - 1:
                e['done'] = True
            else:
                obs_ids = qtok(obs_text(observations), add_special_tokens=False).input_ids
                e['ids'] += obs_ids
                e['mask'] += [0] * len(obs_ids)
                e['logp'] += [0.0] * len(obs_ids)
                e['turn'] += [turn] * len(obs_ids)
                e['texts'].append(obs_text(observations))
    grades = list(pool.map(lambda e: grade(e['repo']), eps))
    trajs = []
    for e, g in zip(eps, grades):
        info = dict(task=e['repo'].task.name, family=e['repo'].task.family, fn=e['repo'].task.fn_name,
                    answered=e['answered'], stats=dict(e['stats']), texts=e['texts'],
                    final_source=e['repo'].files.get(f"{e['repo'].task.fn_name}.py"), **g)
        trajs.append(arl.Trajectory(ids=torch.tensor(e['ids']), action_mask=torch.tensor(e['mask'][1:], dtype=torch.float),
                                    sample_logp=torch.tensor(e['logp'][1:]), reward=float(g['hidden_pass']), info=info,
                                    turn=torch.tensor(e['turn'])))
    return trajs


