def token_log_probs(model, batch, rows):
    """Trainer log-probs of ids[:, 1:] for rows -> (logp [b, T-1], summed entropy); LM head on policy positions only."""
    ids = batch['ids'][rows].cuda()
    hidden = model.model(input_ids=ids, attention_mask=batch['attention_mask'][rows].long().cuda(),
                         use_cache=False).last_hidden_state[:, :-1]                     # [b, T-1, D]
    mask = batch['action_mask'][rows].cuda() > 0                                       # [b, T-1]
    logits = model.lm_head(hidden[mask])                                               # [N, V]
    picked = arl.selected_log_probs(logits, ids[:, 1:][mask])                          # [N]
    logp = torch.zeros(mask.shape, device=ids.device).masked_scatter(mask, picked)
    with torch.no_grad():
        ent = arl.entropy_from_logits(logits.detach()).sum().item()
    return logp, ent


def grpo_update(model, optimizer, trajs, cfg, args):
    """One GRPO step: trainer-recomputed old_logp, group advantages, cfg.minibatches clipped steps."""
    batch = arl.collate(trajs, PAD)
    advantages = arl.compute_advantages(batch, cfg)                                   # [B]
    mask = batch['action_mask']
    old_logp = torch.zeros_like(batch['sample_logp'])
    with torch.no_grad():
        for rows in torch.arange(len(trajs)).split(args.micro):
            old_logp[rows] = token_log_probs(model, batch, rows)[0].float().cpu()
    stats = dict(clip_frac=0.0, approx_kl=0.0, entropy=0.0, grad_norm=0.0, tokens=0.0)
    gap = (old_logp - batch['sample_logp']).abs()[mask > 0]
    for chunk in torch.randperm(len(trajs), generator=torch.Generator().manual_seed(args.seed)).chunk(cfg.minibatches):
        n_tokens = mask[chunk].sum().item()
        optimizer.zero_grad()
        live = chunk[advantages[chunk] != 0]
        for rows in (live.split(args.micro) if len(live) else []):
            logp, ent = token_log_probs(model, batch, rows)
            loss, s = arl.ppo_policy_loss(logp, old_logp[rows].cuda(), advantages[rows].cuda(), mask[rows].cuda(),
                                          cfg.clip_low, cfg.clip_high, mode='constant', norm_const=n_tokens)
            loss.backward()
            w = mask[rows].sum().item()
            stats['clip_frac'] += s['clip_frac'] * w
            stats['approx_kl'] += s['approx_kl'] * w
            stats['entropy'] += ent
            stats['tokens'] += w
        stats['grad_norm'] += float(torch.nn.utils.clip_grad_norm_(model.parameters(), cfg.max_grad_norm))
        optimizer.step()
    t = max(stats.pop('tokens'), 1.0)
    return dict(clip_frac=stats['clip_frac'] / t, approx_kl=stats['approx_kl'] / t, entropy=stats['entropy'] / t,
                grad_norm=stats['grad_norm'] / cfg.minibatches, logp_gap_mean=gap.mean().item(),
                logp_gap_max=gap.max().item(),
                zero_adv_frac=(advantages.view(-1, cfg.group_size) == 0).all(-1).float().mean().item())


# ---------------------------------------------------------------- statistics and evaluation
COUNTED = ['calls_Read', 'calls_Edit', 'calls_Write', 'calls_Bash', 'malformed', 'failed', 'failed_not_found',
           'failed_not_unique', 'failed_not_read', 'failed_no_change', 'failed_missing_file', 'failed_unavailable',
           'failed_bad_path', 'failed_other', 'truncated', 'turns', 'source_changed']


def summarize(trajs):
    """Per-episode averages of rewards, tool calls, failures, and how episodes ended."""
    n = len(trajs)
    out = {k: sum(t.info['stats'].get(k, 0) for t in trajs) / n for k in COUNTED}
    out.update(reward=sum(t.reward for t in trajs) / n, public_pass=sum(t.info['public_pass'] for t in trajs) / n,
               answered=sum(t.info['answered'] for t in trajs) / n,
               policy_tokens=sum(float(t.action_mask.sum()) for t in trajs) / n)
    return out


def evaluate(model, qtok, tasks, cfg, args, n, seed, pool):
    model.eval()
    trajs = rollout(model, qtok, [t for t in tasks for _ in range(n)], cfg, args, seed, pool)
    passed = torch.tensor([t.reward for t in trajs])
    return passed.view(len(tasks), n).sum(-1), summarize(trajs), trajs


def report(name, counts, n, stats):
    rates = counts / n
    lo, hi = arl.bootstrap_ci(rates)
    print(f"{name:<18} pass@1 {rates.mean():.3f} [{lo:.3f}, {hi:.3f}] | Read {stats['calls_Read']:.2f} | Edit "
          f"{stats['calls_Edit']:.2f} | Write {stats['calls_Write']:.2f} | Bash {stats['calls_Bash']:.2f} | malformed "
          f"{stats['malformed']:.2f} | failed {stats['failed']:.2f} | answered {stats['answered']:.2f} | turns "
          f"{stats['turns']:.2f}", flush=True)
    return dict(pass_at_1=rates.mean().item(), ci=[lo, hi], per_task=counts.tolist(), **stats)


def example(t):
    return dict(task=t.info['task'], fn=t.info['fn'], reward=t.reward, answered=t.info['answered'],
                stats=t.info['stats'], final_source=t.info['final_source'], transcript=t.info['texts'])


def main():
    global IM_END, ENDOFTEXT, PAD
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--steps', type=int, default=20)
    p.add_argument('--group-size', type=int, default=8)
    p.add_argument('--prompts', type=int, default=8)
    p.add_argument('--lr', type=float, default=1e-6)
    p.add_argument('--max-turns', type=int, default=6)
    p.add_argument('--max-new-tokens', type=int, default=256)
    p.add_argument('--gen-batch', type=int, default=16, help='rows per generate call (bounds KV-cache memory)')
    p.add_argument('--micro', type=int, default=4)
    p.add_argument('--eval-n', type=int, default=8)
    p.add_argument('--seed', type=int, default=0)
    p.add_argument('--smoke', action='store_true', help='check the template and tools, run 2 eval episodes, exit')
    p.add_argument('--out', default='tutorial/labs/results/qwen_grpo_tools.json')
    args = p.parse_args()
    started = time.time()
    torch.manual_seed(args.seed)
    random.seed(args.seed)
    qtok = AutoTokenizer.from_pretrained(MODEL)
    IM_END, ENDOFTEXT = qtok.convert_tokens_to_ids('<|im_end|>'), qtok.convert_tokens_to_ids('<|endoftext|>')
    PAD = qtok.pad_token_id
    check_template(qtok)
    model = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.float32).cuda()
    model.generation_config.top_k, model.generation_config.top_p = None, None     # sampler = trainer distribution
    model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={'use_reentrant': False})
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=0.0)
    cfg = arl.RLConfig(group_size=args.group_size, prompts_per_step=args.prompts, lr=args.lr, seed=args.seed,
                       max_turns=args.max_turns)
    train, heldout = arl.make_tasks('train'), arl.make_tasks('heldout')
    pool = concurrent.futures.ThreadPoolExecutor(16)
    print(f'config: {dataclasses.asdict(cfg)} | {vars(args)} | prompt tokens {len(prompt_ids(qtok, train[0]))}', flush=True)
    if args.smoke:
        _, stats, trajs = evaluate(model, qtok, heldout, cfg, args, 4, seed=1, pool=pool)
        print(json.dumps(stats, indent=1))
        for t in trajs[::7]:
            print('-' * 80, t.info['task'], t.reward, '\n', ''.join(t.info['texts']))
        print(f'{time.time() - started:.0f}s | peak GPU memory {torch.cuda.max_memory_allocated() / 2 ** 30:.1f} GB')
        return
    result = dict(config=dict(rl=dataclasses.asdict(cfg), lab=vars(args), model=MODEL, tools=TOOLS, system=SYSTEM,
                              limits=LIMITS, torch=torch.__version__, gpu=torch.cuda.get_device_name()), steps=[])
    counts, stats, trajs = evaluate(model, qtok, heldout, cfg, args, args.eval_n, seed=10_000, pool=pool)
    result['before'] = report('held-out, before', counts, args.eval_n, stats)
    result['before_examples'] = [example(t) for t in trajs[::args.eval_n]]
    before_counts = counts
    order = random.Random(args.seed)
    for step in range(args.steps):
        t0 = time.time()
        model.eval()
        picked = order.sample(train, cfg.prompts_per_step)
        trajs = rollout(model, qtok, [t for t in picked for _ in range(cfg.group_size)], cfg, args, step, pool)
        t1 = time.time()
        model.train()
        update = grpo_update(model, optimizer, trajs, cfg, args)
        torch.cuda.empty_cache()
        row = dict(step=step, **summarize(trajs), **update, rollout_s=t1 - t0, update_s=time.time() - t1)
        result['steps'].append(row)
        print(f"step {step:2d} | reward {row['reward']:.3f} | Read {row['calls_Read']:.2f} | Edit {row['calls_Edit']:.2f}"
              f" | Write {row['calls_Write']:.2f} | Bash {row['calls_Bash']:.2f} | malformed {row['malformed']:.2f}"
              f" | failed {row['failed']:.2f} | answered {row['answered']:.2f} | turns {row['turns']:.2f} | tokens"
              f" {row['policy_tokens']:.0f} | zero-adv {row['zero_adv_frac']:.2f} | entropy {row['entropy']:.3f}"
              f" | kl {row['approx_kl']:.1e} | gap {row['logp_gap_mean']:.1e} | {row['rollout_s']:.0f}s +"
              f" {row['update_s']:.0f}s", flush=True)
        if step == 0:
            result['step0_examples'] = [example(t) for t in trajs[::cfg.group_size]]
    counts, stats, trajs = evaluate(model, qtok, heldout, cfg, args, args.eval_n, seed=10_000, pool=pool)
    result['after'] = report('held-out, after', counts, args.eval_n, stats)
    diff, lo, hi = arl.paired_bootstrap_diff(counts / args.eval_n, before_counts / args.eval_n)
    result['paired_diff'] = dict(diff=diff, ci=[lo, hi])
    print(f'paired held-out difference (after - before, {len(heldout)} tasks): {diff:+.3f} [{lo:+.3f}, {hi:+.3f}]')
    result['after_examples'] = [example(t) for t in trajs[::args.eval_n]]
    result['wall_clock_s'] = time.time() - started
    result['peak_gpu_gb'] = torch.cuda.max_memory_allocated() / 2 ** 30
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(result, indent=1))
    print(f"wrote {args.out} | {result['wall_clock_s'] / 60:.1f} min | peak GPU memory {result['peak_gpu_gb']:.1f} GB")


if __name__ == '__main__':
    main()
