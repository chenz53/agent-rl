"""GRPO with Qwen3-0.6B on BugFix tasks through Claude Code-style tools: the realistic variant of Chapter 19's lab.

`qwen_grpo_bugfix.py` gives the model the gym's menu of authored edits (`edit swap_minmax`). Real coding
agents do not get such a menu. They get generic tools and write the change themselves. This script keeps
the tasks, the hidden-test reward, the group advantages, and the clipped loss of the book, and replaces the
action interface with four tools named and parameterized as in Claude Code:

    Read(file_path, offset?, limit?)                       file contents with line numbers (cat -n)
    Edit(file_path, old_string, new_string, replace_all?)  exact string replacement; the file must be Read first
    Write(file_path, content)                              overwrite or create a file; existing files must be Read first
    Bash(command, timeout?)                                an allowlisted emulation: pytest, python <file>.py, ls, cat, grep

Each episode gets an in-memory repository with the buggy source file `<fn>.py` and a public test file
`test_<fn>.py`. The hidden tests never appear in the repository. The episode ends when the assistant replies
without a tool call (its final answer) or when the turn budget runs out, and the reward is 1 if the final
`<fn>.py` passes every hidden test.

Execution note. The model now writes code that runs, the case Chapter 4 says needs isolation. Every test run
and every `python <file>.py` happens in a separate process (`sandbox_run`): a fresh temporary directory, a
wall-clock timeout, resource limits set with the `resource` module before any repository code is imported
(CPU seconds, address space, file size, no child processes), an empty environment, and `python -I -S`.
Nothing the model writes is ever passed to `exec` in this process. This is process isolation with resource
limits on a controlled host, NOT a security sandbox: the child can still read files the user can read and
open network connections. Production systems run model-written code in containers or VMs with no network
access (Chapter 4).

Requirements: Linux, a CUDA GPU, a local Hugging Face cache containing Qwen/Qwen3-0.6B (HF_HUB_OFFLINE=1),
torch, transformers, and `agentrl` generated by `python3 scripts/build_library.py`. From the repository root:

    HF_HUB_OFFLINE=1 python tutorial/labs/qwen_grpo_tools.py --steps 18 --lr 1e-6 --eval-n 8
"""
