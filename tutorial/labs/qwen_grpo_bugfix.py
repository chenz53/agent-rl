"""GRPO on the BugFix gym with Qwen3-0.6B: the optional real-model lab of Chapter 19.

The same recipe as the book's TinyAgent runs, with a pretrained model in place of TinyAgent:
group sampling on training tasks, group-normalized advantages, PPO's clipped token-level
surrogate with a token-mean normalizer, and a held-out evaluation before and after training.
The gym, the tasks, the rewards, the advantage, and the loss come from `agentrl`; this file
adds only what a real model needs: the Qwen3 chat template with tool schemas, a token-in/
token-out rollout, batched generation with Hugging Face `generate`, and microbatched updates.

Requirements: a CUDA GPU, a local Hugging Face cache containing Qwen/Qwen3-0.6B (nothing is
downloaded; HF_HUB_OFFLINE=1), torch and transformers, and `agentrl` generated by
`python3 scripts/build_library.py`. Run from the repository root:

    HF_HUB_OFFLINE=1 python tutorial/labs/qwen_grpo_bugfix.py --steps 20 --out tutorial/labs/results/qwen_grpo_bugfix.json

Execution note: tool calls run the gym's own authored code inside this process. The model only
chooses among fixed edit operations; it never writes code that is executed. A system that runs
model-written code needs the sandboxing of Chapter 4.
"""
import argparse
import dataclasses
import json
import os
import random
import re
import sys
import time
from pathlib import Path

os.environ.setdefault('HF_HUB_OFFLINE', '1')
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import agentrl as arl  # noqa: E402

MODEL = 'Qwen/Qwen3-0.6B'
TOOLS = [{'type': 'function', 'function': {'name': s['name'], 'description': s['description'],
                                           'parameters': s['inputSchema']}} for s in arl.TOOL_SCHEMAS]
INSTRUCTION = ('Find and fix the bug in this function with the tools. The function cannot be seen '
               'until you read it. Only the first edit is applied. Call submit when you are done.')
OBS_TEMPLATE = ('\n<|im_start|>user\n<tool_response>\n{obs}\n</tool_response><|im_end|>\n'
                '<|im_start|>assistant\n<think>\n\n</think>\n\n')
CALL = re.compile(r'<tool_call>\s*(\{.*?\})\s*</tool_call>', re.S)


# ---------------------------------------------------------------- template and token path
def prompt_ids(qtok, task):
    """Template + issue tokens up to the open assistant turn (non-thinking mode) -> list of ids."""
    messages = [{'role': 'user', 'content': f'{task.issue}\n{INSTRUCTION}'}]
    text = qtok.apply_chat_template(messages, tools=TOOLS, tokenize=False, add_generation_prompt=True,
                                    enable_thinking=False)
    return qtok(text, add_special_tokens=False).input_ids


def observation_ids(qtok, obs):
    """Template-owned tokens that close a turn, carry a tool result, and open the next assistant turn."""
    return qtok(OBS_TEMPLATE.format(obs=obs), add_special_tokens=False).input_ids


def check_template(qtok):
    """Assert that appending observation_ids reproduces the real template's rendering, token for token."""
    task = arl.make_tasks('train')[0]
    call = [{'type': 'function', 'function': {'name': 'read', 'arguments': {}}}]
    messages = [{'role': 'user', 'content': f'{task.issue}\n{INSTRUCTION}'},
                {'role': 'assistant', 'content': '', 'tool_calls': call},
                {'role': 'tool', 'content': 'def f ( x ) :'}]
    full = qtok.apply_chat_template(messages, tools=TOOLS, tokenize=False, add_generation_prompt=True,
                                    enable_thinking=False)
    cut = full.index('<|im_end|>', full.index('<|im_start|>assistant')) + len('<|im_end|>')
    assert full[cut:] == OBS_TEMPLATE.format(obs='def f ( x ) :'), repr(full[cut:])
    ids = qtok(full, add_special_tokens=False).input_ids
    head = qtok(full[:cut], add_special_tokens=False).input_ids
    assert ids == head + observation_ids(qtok, 'def f ( x ) :'), 'token boundary differs'


def to_gym_action(text):
    """First <tool_call> JSON of an assistant turn -> the gym's '<call> tool [op] </call>' ('' if malformed)."""
    match = CALL.search(text)
    try:
        call = json.loads(match.group(1)) if match else None
    except json.JSONDecodeError:
        return ''
    if not isinstance(call, dict) or not isinstance(call.get('arguments', {}), dict):
        return ''
    op = call.get('arguments', {}).get('op')
    return f"<call> {call.get('name')} {op} </call>" if op else f"<call> {call.get('name')} </call>"


# ---------------------------------------------------------------- rollout (token-in/token-out)
@torch.no_grad()
def generate(model, qtok, prefixes, max_new_tokens, generator_seed):
    """One assistant turn for each prefix (lists of ids), left-padded -> (new ids, sampler log-probs) per row."""
    width = max(len(p) for p in prefixes)
    ids = torch.tensor([[qtok.pad_token_id] * (width - len(p)) + p for p in prefixes], device='cuda')
    attn = torch.tensor([[0] * (width - len(p)) + [1] * len(p) for p in prefixes], device='cuda')
    torch.manual_seed(generator_seed)
    out = model.generate(input_ids=ids, attention_mask=attn, do_sample=True, temperature=1.0, top_p=1.0,
                         top_k=0, max_new_tokens=max_new_tokens, eos_token_id=[IM_END, ENDOFTEXT],
                         pad_token_id=qtok.pad_token_id, output_logits=True, return_dict_in_generate=True)
    new = out.sequences[:, width:]                                           # [B, n]
    logp = torch.stack([torch.log_softmax(l.float(), -1) for l in out.logits], 1)   # [B, n, V]
    logp = logp.gather(-1, new.unsqueeze(-1)).squeeze(-1)                    # [B, n]
    rows = []
    for b in range(len(prefixes)):
        row = new[b].tolist()
        end = next((i + 1 for i, t in enumerate(row) if t in (IM_END, ENDOFTEXT)), len(row))
        rows.append((row[:end], logp[b, :end].tolist()))
    return rows


def rollout(model, qtok, tasks, cfg, args, seed):
    """Episodes for tasks in lockstep -> list of arl.Trajectory (ids, action_mask, sample_logp, reward, info)."""
    names = random.Random(seed)
    tasks = [arl.randomize_names(t, names) if cfg.rename else t for t in tasks]
    envs = [arl.make_env(cfg) for _ in tasks]
    eps = []
    for env, task in zip(envs, tasks):
        env.reset(task)
        ids = prompt_ids(qtok, task)
        eps.append(dict(env=env, ids=ids, mask=[0] * len(ids), logp=[0.0] * len(ids), turn=[-1] * len(ids),
                        actions=[], done=False))
    for turn in range(cfg.max_turns):
        active = [e for e in eps if not e['done']]
        if not active:
            break
        for e, (new, logp) in zip(active, generate(model, qtok, [e['ids'] for e in active],
                                                   args.max_new_tokens, seed * 100 + turn)):
            if new[-1] != IM_END:                     # cut off at max_new_tokens: close the turn (template-owned)
                new_mask, new = [1] * len(new) + [0], new + [IM_END]
                logp = logp + [0.0]
            else:
                new_mask = [1] * len(new)
            e['ids'] += new
            e['mask'] += new_mask
            e['logp'] += logp
            e['turn'] += [turn] * len(new)
            e['actions'].append(to_gym_action(qtok.decode(new)))
            obs, reward, done, info = e['env'].step(e['actions'][-1])
            if done:
                e.update(done=True, reward=reward, info=info)
            else:
                obs_ids = observation_ids(qtok, obs)
                e['ids'] += obs_ids
                e['mask'] += [0] * len(obs_ids)
                e['logp'] += [0.0] * len(obs_ids)
                e['turn'] += [turn] * len(obs_ids)
    return [arl.Trajectory(ids=torch.tensor(e['ids']), action_mask=torch.tensor(e['mask'][1:], dtype=torch.float),
                           sample_logp=torch.tensor(e['logp'][1:]), reward=float(e['reward']),
                           info=dict(e['info'], actions=e['actions']), turn=torch.tensor(e['turn'])) for e in eps]


# ---------------------------------------------------------------- update
def token_log_probs(model, batch, rows):
    """Trainer log-probs of ids[:, 1:] for a microbatch of rows -> (logp [b, T-1], summed entropy on policy tokens).

    Logits are computed only at policy positions: [b, T, 151936] fp32 logits would cost ~0.6 GB per row
    of 1,000 tokens (Chapter 14), while the loss needs only the few hundred positions the model generated.
    """
    ids = batch['ids'][rows].cuda()
    hidden = model.model(input_ids=ids, attention_mask=batch['attention_mask'][rows].long().cuda()
                         ).last_hidden_state[:, :-1]                             # [b, T-1, D]
    mask = batch['action_mask'][rows].cuda() > 0                                # [b, T-1]
    logits = model.lm_head(hidden[mask])                                        # [N, V], N policy tokens
    picked = arl.selected_log_probs(logits, ids[:, 1:][mask])                   # [N]
    logp = torch.zeros(mask.shape, device=ids.device).masked_scatter(mask, picked)   # [b, T-1], 0 off-policy
    with torch.no_grad():
        ent = arl.entropy_from_logits(logits.detach()).sum().item()
    return logp, ent


def grpo_update(model, optimizer, trajs, cfg, args):
    """One GRPO step: trainer-recomputed old_logp, group advantages, cfg.minibatches clipped steps."""
    batch = arl.collate(trajs, PAD)
    advantages = arl.compute_advantages(batch, cfg)                              # [B]
    mask = batch['action_mask']                                                  # [B, T-1]
    old_logp = torch.zeros_like(batch['sample_logp'])
    with torch.no_grad():
        for rows in torch.arange(len(trajs)).split(args.micro):
            old_logp[rows] = token_log_probs(model, batch, rows)[0].float().cpu()
    stats = dict(clip_frac=0.0, approx_kl=0.0, entropy=0.0, grad_norm=0.0, tokens=0.0)
    gap = (old_logp - batch['sample_logp']).abs()[mask > 0]
    for chunk in torch.randperm(len(trajs), generator=torch.Generator().manual_seed(args.seed)).chunk(cfg.minibatches):
        n_tokens = mask[chunk].sum().item()          # token_mean over the whole minibatch, not per microbatch
        optimizer.zero_grad()
        live = chunk[advantages[chunk] != 0]          # zero-advantage rows add tokens to the normalizer only
        for rows in (live.split(args.micro) if len(live) else []):
            logp, ent = token_log_probs(model, batch, rows)
            loss, s = arl.ppo_policy_loss(logp, old_logp[rows].cuda(), advantages[rows].cuda(), mask[rows].cuda(),
                                          cfg.clip_low, cfg.clip_high, mode='constant', norm_const=n_tokens)
            loss.backward()
            w = mask[rows].sum().item()
            stats['clip_frac'] += s['clip_frac'] * w
            stats['approx_kl'] += s['approx_kl'] * w
            stats['entropy'] += ent
            stats['tokens'] += w
        stats['grad_norm'] += float(torch.nn.utils.clip_grad_norm_(model.parameters(), cfg.max_grad_norm))
        optimizer.step()
    t = max(stats.pop('tokens'), 1.0)
    return dict(clip_frac=stats['clip_frac'] / t, approx_kl=stats['approx_kl'] / t, entropy=stats['entropy'] / t,
                grad_norm=stats['grad_norm'] / cfg.minibatches, logp_gap_mean=gap.mean().item(),
                logp_gap_max=gap.max().item(), zero_adv_frac=(advantages.view(-1, cfg.group_size) == 0)
                .all(-1).float().mean().item())


def summarize(trajs):
    """Behavior statistics of the book (Chapter 9) plus malformed calls and submissions per episode."""
    n = len(trajs)
    return dict(arl.behavior_stats(trajs), malformed=sum(t.info['n_invalid'] for t in trajs) / n,
                submitted=sum(bool(t.info['submitted']) for t in trajs) / n)


def evaluate(model, qtok, tasks, cfg, args, n, seed):
    """n sampled episodes per task -> (per-task successes [N], behavior statistics)."""
    model.eval()
    trajs = rollout(model, qtok, [t for t in tasks for _ in range(n)], cfg, args, seed)
    passed = torch.tensor([bool(t.info['submitted'] and t.info['hidden_pass']) for t in trajs], dtype=torch.float)
    return passed.view(len(tasks), n).sum(-1), summarize(trajs), trajs


def policy_text(qtok, traj):
    """Decoded policy-owned tokens of one episode, one string per assistant turn."""
    ids, mask, turn = traj.ids[1:], traj.action_mask > 0, traj.turn[1:]
    return [qtok.decode(ids[mask & (turn == k)]) for k in range(int(turn.max()) + 1)]


def report(name, counts, n, stats):
    rates = counts / n
    lo, hi = arl.bootstrap_ci(rates)
    print(f"{name:<22} pass@1 {rates.mean():.3f} [{lo:.3f}, {hi:.3f}] | reads {stats['reads']:.2f} | edits "
          f"{stats['edits']:.2f} | first edit right {stats['first_edit_right']:.2f} | malformed "
          f"{stats['malformed']:.2f} | submitted {stats['submitted']:.2f}", flush=True)
    return dict(pass_at_1=rates.mean().item(), ci=[lo, hi], per_task=counts.tolist(), **stats)


def main():
    global IM_END, ENDOFTEXT, PAD
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--steps', type=int, default=20)
    p.add_argument('--group-size', type=int, default=8)
    p.add_argument('--prompts', type=int, default=8)
    p.add_argument('--lr', type=float, default=2e-6)
    p.add_argument('--max-new-tokens', type=int, default=64)
    p.add_argument('--micro', type=int, default=8)
    p.add_argument('--eval-n', type=int, default=8)
    p.add_argument('--seed', type=int, default=0)
    p.add_argument('--out', default='tutorial/labs/results/qwen_grpo_bugfix.json')
    args = p.parse_args()
    started = time.time()
    torch.manual_seed(args.seed)
    qtok = AutoTokenizer.from_pretrained(MODEL)
    IM_END, ENDOFTEXT = qtok.convert_tokens_to_ids('<|im_end|>'), qtok.convert_tokens_to_ids('<|endoftext|>')
    PAD = qtok.pad_token_id
    check_template(qtok)
    model = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.float32).cuda()
    model.generation_config.top_k, model.generation_config.top_p = None, None    # sampler = trainer distribution
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=0.0)
    cfg = arl.RLConfig(group_size=args.group_size, prompts_per_step=args.prompts, lr=args.lr, seed=args.seed)
    train, heldout = arl.make_tasks('train'), arl.make_tasks('heldout')
    print(f'config: {dataclasses.asdict(cfg)} | {vars(args)}', flush=True)
    result = dict(config=dict(rl=dataclasses.asdict(cfg), lab=vars(args), model=MODEL,
                              torch=torch.__version__, gpu=torch.cuda.get_device_name()), steps=[])
    counts, stats, trajs = evaluate(model, qtok, heldout, cfg, args, args.eval_n, seed=10_000)
    result['before'] = report('held-out, before', counts, args.eval_n, stats)
    result['before_text'] = [policy_text(qtok, t) for t in trajs[:2]]
    before_counts = counts
    order = random.Random(args.seed)
    for step in range(args.steps):
        t0 = time.time()
        model.eval()
        picked = order.sample(train, cfg.prompts_per_step)
        trajs = rollout(model, qtok, [t for t in picked for _ in range(cfg.group_size)], cfg, args, seed=step)
        t1 = time.time()
        model.train()
        update = grpo_update(model, optimizer, trajs, cfg, args)
        row = dict(step=step, **summarize(trajs), **update, rollout_s=t1 - t0, update_s=time.time() - t1,
                   policy_tokens=sum(float(t.action_mask.sum()) for t in trajs) / len(trajs))
        result['steps'].append(row)
        print(f"step {step:2d} | reward {row['reward']:.3f} | reads {row['reads']:.2f} | edits {row['edits']:.2f}"
              f" | malformed {row['malformed']:.2f} | zero-adv {row['zero_adv_frac']:.2f} | entropy {row['entropy']:.3f}"
              f" | kl {row['approx_kl']:.2e} | gap {row['logp_gap_mean']:.1e} | {row['rollout_s']:.0f}s +"
              f" {row['update_s']:.0f}s", flush=True)
    counts, stats, trajs = evaluate(model, qtok, heldout, cfg, args, args.eval_n, seed=10_000)
    result['after'] = report('held-out, after', counts, args.eval_n, stats)
    diff, lo, hi = arl.paired_bootstrap_diff(counts / args.eval_n, before_counts / args.eval_n)
    result['paired_diff'] = dict(diff=diff, ci=[lo, hi])
    print(f'paired held-out difference (after - before, 10 tasks): {diff:+.3f} [{lo:+.3f}, {hi:+.3f}]')
    result['after_text'] = [policy_text(qtok, t) for t in trajs[:2]]
    result['examples'] = [dict(task=t.info['task'], actions=t.info['actions'], passed=bool(t.reward))
                          for t in trajs[::args.eval_n]]
    result['wall_clock_s'] = time.time() - started
    result['peak_gpu_gb'] = torch.cuda.max_memory_allocated() / 2 ** 30
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(result, indent=1))
    print(f"wrote {args.out} | {result['wall_clock_s'] / 60:.1f} min | peak GPU memory {result['peak_gpu_gb']:.1f} GB")


if __name__ == '__main__':
    main()
