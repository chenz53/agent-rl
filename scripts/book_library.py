"""Build the book's module graph from chapter-owned #@save blocks.

Shared by the on-disk generator and the chapter checker. No PyTorch import is
needed to inspect or generate the package. Executing it needs the book's runtime.
"""
import ast
import builtins
from dataclasses import dataclass
from pathlib import Path
import re
import symtable
import sys
import textwrap
import types

ROOT = Path(__file__).resolve().parents[1]
CHAPTERS = ROOT / 'tutorial' / 'chapters'
BLOCK = re.compile(
    r'```python\n(?P<code>.*?)\n```(?P<tail>\n\nOutput:\n\n```text\n(?P<output>.*?)\n```)?',
    re.S,
)
SAVE_ALLOWED = (ast.Import, ast.ImportFrom, ast.FunctionDef, ast.ClassDef,
                ast.Assign, ast.AnnAssign, ast.Expr)
GENERATED = 'GENERATED by scripts/build_library.py'

# One chapter owns each topic. Adding saved code in a new chapter requires an
# explicit home here, so package organization does not depend on filename guesses.
CHAPTER_MODULES = {
    '01': 'examples', '02': 'mdp', '03': 'policy', '04': 'environments',
    '05': 'trajectories', '06': 'policy_gradient', '07': 'advantages',
    '08': 'ppo', '09': 'grpo', '10': 'regularization', '11': 'rewards',
    '12': 'multiturn', '13': 'rollout_systems', '14': 'efficiency',
    '15': 'sft', '16': 'distillation', '17': 'evaluation', '18': 'debugging',
    'A': 'math_utils',
}


def chapter_paths():
    return sorted(CHAPTERS.glob('*.md'))


def saved_blocks(path):
    return [m['code'] for m in BLOCK.finditer(path.read_text())
            if m['code'].lstrip().startswith('#@save')]


def validate_saved(path, code):
    for node in ast.parse(code).body:
        if not isinstance(node, SAVE_ALLOWED):
            raise ValueError(f'{path.name}: #@save block may only define names, got {type(node).__name__}')
        if isinstance(node, ast.Expr) and not isinstance(getattr(node, 'value', None), ast.Constant):
            raise ValueError(f'{path.name}: #@save block may not call functions at top level')


def assigned_names(node):
    """Names defined by a module-level assignment, including tuple unpacking."""
    targets = node.targets if isinstance(node, ast.Assign) else [node.target]
    return [n.id for target in targets for n in ast.walk(target)
            if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store)]


def defined_names(tree):
    names = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.append(node.name)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            names.extend(assigned_names(node))
    return names


def import_bindings(node):
    """Separate imports by bound name, retaining explicit aliases."""
    if isinstance(node, ast.Import):
        return {a.asname or a.name.split('.')[0]: ast.unparse(ast.Import(names=[a])) for a in node.names}
    return {a.asname or a.name: ast.unparse(ast.ImportFrom(module=node.module, names=[a], level=node.level))
            for a in node.names}


def global_references(code):
    names = set()

    def visit(table):
        # Python 3.12+ inlines comprehensions; their iteration variables can be
        # marked global in the enclosing symbol table, but are assigned there.
        names.update(s.get_name() for s in table.get_symbols()
                     if s.is_global() and s.is_referenced()
                     and (not s.is_assigned() or s.is_declared_global()))
        for child in table.get_children():
            visit(child)

    visit(symtable.symtable(code, '<saved blocks>', 'exec'))
    return names


def redirect_references(code, owners, module_name):
    """Change only the `arl` prefix of arl.name to its defining module alias.

    This uses source spans instead of ast.unparse so function bodies, comments,
    formatting and docstrings survive. Module aliases are private to avoid
    shadowing arguments such as `advantages` or `policy`.
    """
    lines = code.splitlines(keepends=True)
    starts, offset = [], 0
    for line in lines:
        starts.append(offset)
        offset += len(line)
    replacements, dependencies = [], set()
    for node in ast.walk(ast.parse(code)):
        if not (isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name)
                and node.value.id == 'arl'):
            continue
        if node.attr not in owners:
            raise ValueError(f'{module_name}: arl.{node.attr} is not saved by an earlier chapter')
        owner = owners[node.attr]
        if owner == module_name:
            raise ValueError(f'{module_name}: use a bare name for a definition in the same chapter: {node.attr}')
        dependencies.add(owner)
        ref = node.value
        # AST columns count UTF-8 bytes; Python string offsets count characters.
        col = len(lines[ref.lineno - 1].encode()[:ref.col_offset].decode())
        begin = starts[ref.lineno - 1] + col
        replacements.append((begin, begin + 3, '_' + owner))
    for start, end, replacement in sorted(replacements, reverse=True):
        code = code[:start] + replacement + code[end:]
    return code, dependencies


@dataclass(frozen=True)
class BookModule:
    name: str
    chapter: Path
    exports: tuple[str, ...]
    dependencies: tuple[str, ...]
    source: str


def string_tuple(names):
    if not names:
        return '()'
    lines = textwrap.wrap(', '.join(repr(n) for n in names), width=88,
                          initial_indent='    ', subsequent_indent='    ', break_long_words=False)
    return '(\n' + '\n'.join(lines) + ',\n)'


def build_modules(paths):
    """Resolve imports and render modules in chapter order; reject forward references."""
    modules, owners, earlier_imports = [], {}, {}
    for path in paths:
        blocks = saved_blocks(path)
        if not blocks:
            continue
        prefix = path.stem.split('-')[0]
        if prefix not in CHAPTER_MODULES:
            raise ValueError(f'{path.name}: add its saved module to CHAPTER_MODULES')
        name = CHAPTER_MODULES[prefix]
        if any(m.name == name for m in modules):
            raise ValueError(f'{path.name}: duplicate module {name}')
        imports, exports, bodies = {}, [], []
        for index, code in enumerate(blocks, 1):
            validate_saved(path, code)
            tree = ast.parse(code)
            exports.extend(defined_names(tree))
            lines = code.splitlines(keepends=True)
            for node in tree.body:
                if isinstance(node, (ast.Import, ast.ImportFrom)):
                    imports.update(import_bindings(node))
                    lines[node.lineno - 1:node.end_lineno] = [''] * (node.end_lineno - node.lineno + 1)
            body = ''.join(lines).removeprefix('#@save').strip()
            if body:
                bodies.append((index, body))
        if len(exports) != len(set(exports)) or any(n in owners for n in exports):
            raise ValueError(f'{path.name}: a saved definition shadows another saved name')
        dependencies, rendered = set(), []
        for index, body in bodies:
            body, deps = redirect_references(body, owners, name)
            dependencies.update(deps)
            rendered.append(f'# Source: tutorial/chapters/{path.name}, saved block {index}\n{body}\n')
        raw = '\n\n'.join(body for _, body in bodies)
        extra_imports = []
        for needed in sorted(global_references(raw) - set(exports) - set(imports) - set(dir(builtins))):
            if needed in earlier_imports:
                extra_imports.append(earlier_imports[needed])
            elif needed in owners:
                dependencies.add(owners[needed])
                extra_imports.append(f'from .{owners[needed]} import {needed}')
            else:
                raise ValueError(f'{path.name}: unresolved saved global {needed}')
        # Dynamic package access cannot be resolved into an explicit dependency.
        for body in rendered:
            if any(isinstance(n, ast.Name) and n.id == 'arl' for n in ast.walk(ast.parse(body))):
                raise ValueError(f'{path.name}: dynamic arl access has no explicit module dependency')
        ordered_deps = tuple(m.name for m in modules if m.name in dependencies)
        import_lines = [f'from . import {d} as _{d}' for d in ordered_deps]
        import_lines += [value for key, value in imports.items() if key != 'arl'] + extra_imports
        import_lines = list(dict.fromkeys(import_lines))
        header = (f'"""{name}: code taught in {path.name}.\n\n'
                  f'{GENERATED} from the chapter\'s #@save blocks.\n'
                  'Do not edit by hand; edit the chapter and rebuild.\n"""\n')
        source = header + '\n' + '\n'.join(import_lines) + '\n\n'
        source += '__all__ = ' + string_tuple(exports) + '\n\n\n' + '\n\n'.join(rendered)
        compile(source, f'agentrl/{name}.py', 'exec')
        modules.append(BookModule(name, path, tuple(exports), ordered_deps, source))
        owners.update(dict.fromkeys(exports, name))
        earlier_imports.update({k: v for k, v in imports.items() if k != 'arl'})
    return modules


def package_source(modules):
    source = ('"""Public API for the Agentic RL book.\n\n'
              f'{GENERATED}; implementations live in the topic modules.\n'
              'Existing `import agentrl as arl` examples use these explicit re-exports.\n"""\n\n')
    if modules:
        names = textwrap.wrap(', '.join(m.name for m in modules), width=88,
                              initial_indent='    ', subsequent_indent='    ', break_long_words=False)
        source += 'from . import (\n' + '\n'.join(names) + ',\n)\n\n'
    for module in modules:
        lines = textwrap.wrap(', '.join(module.exports), width=88,
                              initial_indent='    ', subsequent_indent='    ', break_long_words=False)
        source += f'from .{module.name} import (\n' + '\n'.join(lines) + ',\n)\n'
    source += '\n__all__ = (\n'
    source += ''.join(f'    *{m.name}.__all__,\n' for m in modules)
    return source + ')\n'


def package_readme(modules):
    rows = [
        '# Generated agentrl package\n',
        'Implementations are grouped by topic; `__init__.py` only re-exports the public API. '
        'For example, `agentrl.TinyAgent` and `agentrl.policy.TinyAgent` are the same class.\n',
        'Edit `#@save` blocks in the English chapters, then run '
        '`python3 scripts/build_library.py`. Do not edit generated files. The generator '
        'resolves `arl.name` references into explicit imports from the defining topic module; '
        'it preserves the implementation and comments. Each saved block has a source pointer.\n',
        '| Module | Source chapter |\n| --- | --- |',
    ]
    for m in modules:
        rows.append(f'| [{m.name}.py]({m.name}.py) | [{m.chapter.name}](../tutorial/chapters/{m.chapter.name}) |')
    rows += ['\nDependencies point to earlier chapters. The checker builds the same module '
             'graph in memory, with only chapters preceding the one being checked.\n',
             'Mutable module settings belong to their defining module. For example, change '
             '`agentrl.grpo.FN_NAMES` when temporarily restricting the renaming pool; rebinding '
             'the re-export `agentrl.FN_NAMES` does not change that module\'s setting.\n']
    return '\n'.join(rows)


def package_files(modules):
    return {'__init__.py': package_source(modules), 'README.md': package_readme(modules),
            **{m.name + '.py': m.source for m in modules}}


def make_library(paths):
    """Load the generated modules in memory, without leaking a later chapter."""
    modules = build_modules(paths)  # Validate before replacing the current library.
    for name in list(sys.modules):
        if name == 'agentrl' or name.startswith('agentrl.'):
            del sys.modules[name]
    package = types.ModuleType('agentrl')
    package.__file__ = str(ROOT / 'agentrl' / '__init__.py')
    package.__package__ = 'agentrl'
    package.__path__ = []  # No filesystem fallback to later generated modules.
    sys.modules['agentrl'] = package
    for spec in modules:
        qualified = 'agentrl.' + spec.name
        module = types.ModuleType(qualified)
        module.__file__ = str(ROOT / 'agentrl' / (spec.name + '.py'))
        module.__package__ = 'agentrl'
        sys.modules[qualified] = module  # Required for dataclass type resolution.
        setattr(package, spec.name, module)
        exec(compile(spec.source, module.__file__, 'exec'), module.__dict__)
    exec(compile(package_source(modules), package.__file__, 'exec'), package.__dict__)
    return package
