"""Collect every #@save block from tutorial chapters into the generated agentrl package.

The book builds each function visibly the first time it is taught; later chapters
`import agentrl as arl` instead of repeating the definition (the D2L `d2l` pattern).
Never edit agentrl/__init__.py by hand: edit the chapter and rerun this script.
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_tutorial_snippets import ROOT, chapter_paths, saved_blocks, validate_saved  # noqa: E402

HEADER = '''"""agentrl: functions built in the Agentic RL book.

GENERATED by scripts/build_library.py from the #@save blocks in tutorial/chapters/.
Do not edit by hand. Each section names the chapter that derives the code.
"""
'''


def main():
    parts = [HEADER]
    count = 0
    for path in chapter_paths():
        blocks = saved_blocks(path)
        if not blocks:
            continue
        parts.append(f'\n\n# {"=" * 70}\n# Defined in tutorial/chapters/{path.name}\n# {"=" * 70}\n')
        for code in blocks:
            validate_saved(path, code)
            parts.append('\n' + code.split('\n', 1)[1].strip('\n') + '\n')
            count += 1
    target = ROOT / 'agentrl' / '__init__.py'
    target.parent.mkdir(exist_ok=True)
    target.write_text(''.join(parts))
    print(f'Wrote {count} saved blocks to {target.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
